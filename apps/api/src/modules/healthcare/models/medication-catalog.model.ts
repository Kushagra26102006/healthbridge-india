import mongoose, { Document, Model, Schema } from 'mongoose';

export interface IMedicationCatalogDocument extends Document {
  name: string;
  genericName: string;
  brandName: string;
  dosageForm: string;
  strength: string;
  route: string;
  manufacturer: string;
  category?: string;
  composition?: string;
  packSize?: string;
  unitOfMeasurement?: string;
  packageSize: string;
  schedule: string;
  therapeuticClass?: string;
  standardDosageUnit: string;
  description?: string;
  instructionsHint?: string;
  requiresPrescription: boolean;
  isActive: boolean;
  createdAt: Date;
  updatedAt: Date;
}

const MedicationCatalogSchema = new Schema<IMedicationCatalogDocument>(
  {
    name: {
      type: String,
      required: [true, 'Medication name is required'],
      trim: true,
      index: true,
    },
    genericName: {
      type: String,
      required: [true, 'Generic composition name is required'],
      trim: true,
      index: true,
    },
    brandName: {
      type: String,
      required: [true, 'Brand name is required'],
      trim: true,
      index: true,
    },
    dosageForm: {
      type: String,
      required: [true, 'Dosage form is required'],
      enum: ['TABLET', 'CAPSULE', 'SYRUP', 'INJECTION', 'INHALER', 'OINTMENT', 'DROPS', 'SUSPENSION', 'POWDER'],
      default: 'TABLET',
      index: true,
    },
    strength: {
      type: String,
      required: [true, 'Strength specification is required'],
      trim: true,
    },
    route: {
      type: String,
      required: [true, 'Route of administration is required'],
      default: 'Oral',
      trim: true,
    },
    manufacturer: {
      type: String,
      required: [true, 'Pharmaceutical manufacturer is required'],
      trim: true,
    },
    packageSize: {
      type: String,
      default: 'Strip of 10 tablets',
      trim: true,
    },
    schedule: {
      type: String,
      default: 'Schedule H',
      trim: true,
    },
    therapeuticClass: {
      type: String,
      trim: true,
      index: true,
    },
    category: {
      type: String,
      trim: true,
      default: 'General',
      index: true,
    },
    composition: {
      type: String,
      trim: true,
    },
    packSize: {
      type: String,
      trim: true,
    },
    unitOfMeasurement: {
      type: String,
      default: 'tablet',
      trim: true,
    },
    description: {
      type: String,
      trim: true,
    },
    requiresPrescription: {
      type: Boolean,
      default: true,
      index: true,
    },
    standardDosageUnit: {
      type: String,
      default: 'tablet',
      trim: true,
    },
    instructionsHint: {
      type: String,
      trim: true,
    },
    isActive: {
      type: Boolean,
      default: true,
      index: true,
    },
  },
  {
    timestamps: true,
    collection: 'medication_catalog',
    toJSON: {
      virtuals: true,
      transform: (_doc, ret: Record<string, unknown>) => {
        delete ret.__v;
        ret.id = ret._id;
        delete ret._id;
        return ret;
      },
    },
  }
);

MedicationCatalogSchema.index({ genericName: 1, brandName: 1 });
MedicationCatalogSchema.index({ brandName: 1, strength: 1, dosageForm: 1, manufacturer: 1 }, { unique: true });
MedicationCatalogSchema.index({ dosageForm: 1, isActive: 1 });

export const MedicationCatalogModel: Model<IMedicationCatalogDocument> =
  (mongoose.models.MedicationCatalog as Model<IMedicationCatalogDocument>) ||
  mongoose.model<IMedicationCatalogDocument>('MedicationCatalog', MedicationCatalogSchema);

